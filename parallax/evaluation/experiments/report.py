"""Renders evaluation/results/summary.json as Markdown (report.md).

Every number in the report is read from summary.json; nothing is typed in.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path


def pct(p: dict | None) -> str:
    if not p or p.get("rate") is None:
        return "n/a"
    lo, hi = p["ci95"]
    return f"{100 * p['rate']:.1f}% [{100 * lo:.1f}, {100 * hi:.1f}]"


def num(x, digits=2) -> str:
    return "n/a" if x is None else f"{x:.{digits}f}"


def write_report(s: dict, path: Path) -> None:
    L = []
    env = s["environment"]
    ds = s["dataset"]
    L.append("# IntelliFix evaluation report (generated)\n")
    L.append("> Generated by `python -m evaluation.experiments.run_experiments` from `summary.json`. "
             "Do not edit by hand.\n")
    L.append(f"- Cases: **{s['n_cases']}** ({ds['by_split']}), programs: {ds['programs']}, "
             f"kinds: {ds['by_kind']}")
    L.append(f"- Runtime: {s['runtime_seconds']:.1f} s on {env['cpu_count']} CPUs, {env['platform']}")
    L.append(f"- Compiler: {env['compiler']}, {env['bison']}, {env['flex']}, Python {env['python']}, "
             f"commit `{env['git_commit']}`, {env['timestamp_utc']}")
    ts = s["tau_selection"]
    L.append(f"- Abstention threshold: **tau = {ts['tau']}** chosen on the dev split ({ts['rule']}); "
             f"offline re-threshold check: {ts['offline_rethreshold_check']['agree']}/"
             f"{ts['offline_rethreshold_check']['sample']} statuses identical to a direct `--tau` run.\n")

    for split in ("test", "dev"):
        r = s.get(split)
        if not r:
            continue
        L.append(f"## {split.upper()} split\n")
        L.append("### Repair quality (95% Wilson intervals)\n")
        L.append("| System | Top-1 AST match | Top-1 exact tokens | Top-3 AST match | Output parses | "
                 "Coverage (recommended) | Selective accuracy | False confident rate | AURC (lower=better) |")
        L.append("|---|---|---|---|---|---|---|---|---|")
        for sys_ in s["systems"]:
            sid = sys_["id"]
            if sys_["family"] != "repair":
                continue
            m = r[sid]
            L.append(f"| {sid} {sys_['name']} | {pct(m['top1_ast'])} | {pct(m['top1_exact'])} | {pct(m['top3_ast'])} | "
                     f"{pct(m['output_parser_valid'])} | {pct(m['coverage'])} | {pct(m['selective_accuracy'])} | "
                     f"{pct(m['false_confident_rate'])} | {num(m['aurc'], 3)} (oracle {num(m['oracle_aurc'], 3)}) |")
        L.append("")
        L.append("### Error localisation\n")
        L.append("| System | Exact token | Within 1 token | Same line |")
        L.append("|---|---|---|---|")
        a = r["A"]
        L.append(f"| A Raw parser (detection point) | {pct(a['localisation_exact'])} | {pct(a['localisation_within_1'])} | "
                 f"{pct(a['localisation_same_line'])} |")
        for sid in ("C", "P"):
            m = r[sid]
            L.append(f"| {sid} (first edit of top plan) | {pct(m['localisation_exact'])} | "
                     f"{pct(m['localisation_within_1'])} | {pct(m['localisation_same_line'])} |")
        L.append("")
        b = r["B"]
        L.append("### Panic-mode recovery (B)\n")
        L.append(f"- Diagnostics per case: mean {num(b['diagnostics_per_case']['mean'])}, "
                 f"max {b['diagnostics_per_case']['max']}")
        L.append(f"- Spurious diagnostics (reported minus injected, floored at 0): mean "
                 f"{num(b['spurious_diagnostics_per_case']['mean'])}; cases with any: {pct(b['cases_with_spurious'])}")
        L.append(f"- Multi-error cases where at least as many diagnostics as injected errors were reported: "
                 f"{pct(b['multi_error_all_reported'])}")
        L.append(f"- Lexical-error detection on invalid-character cases (A/B lexer): {pct(a['lexical_error_detection'])}\n")
        L.append("### Cost\n")
        L.append("| System | Candidates generated (mean) | AST classes (mean) | Parser invocations (mean / p95) | "
                 "Engine ms (mean / p95) | End-to-end ms incl. process (mean / p95) | Budget exhausted |")
        L.append("|---|---|---|---|---|---|---|")
        for sys_ in s["systems"]:
            sid = sys_["id"]
            if sys_["family"] != "repair":
                continue
            m = r[sid]
            L.append(f"| {sid} | {num(m['candidates_generated']['mean'], 1)} | {num(m['classes']['mean'], 1)} | "
                     f"{num(m['parser_invocations']['mean'], 0)} / {m['parser_invocations']['p95']} | "
                     f"{num(m['engine_ms']['mean'])} / {num(m['engine_ms']['p95'])} | "
                     f"{num(m['latency_ms']['mean'])} / {num(m['latency_ms']['p95'])} | {pct(m['budget_exhausted'])} |")
        L.append(f"\nRaw parser (A) end-to-end ms: mean {num(a['latency_ms']['mean'])}, p95 {num(a['latency_ms']['p95'])}\n")
        if split == "test":
            L.append("### Status distribution (test, tau applied)\n")
            for sys_ in s["systems"]:
                if sys_["family"] == "repair":
                    L.append(f"- **{sys_['id']}**: {r[sys_['id']]['status_counts']}")
            L.append("")

    cp = s.get("cpctplus") or {}
    L.append("## Optional baseline G: CPCT+ (grmtools nimbleparse)\n")
    if cp.get("test"):
        L.append(f"Availability: {cp['availability']}. {cp['note']}\n")
        L.append(f"Top-1 agreement between the two replicates (all cases): {pct(cp['replicate_top1_agreement'])}\n")
        L.append("| Split / replicate | Top-1 AST match | Top-1 exact tokens | Top-3 AST match | Output parses | "
                 "Localisation exact | Within 1 | Same line | Wall ms (mean / p95) |")
        L.append("|---|---|---|---|---|---|---|---|---|")
        for split in ("test", "dev"):
            for k, m in enumerate(cp.get(split) or []):
                L.append(f"| {split} #{k + 1} | {pct(m['top1_ast'])} | {pct(m['top1_exact'])} | {pct(m['top3_ast'])} | "
                         f"{pct(m['output_parser_valid'])} | {pct(m['localisation_exact'])} | "
                         f"{pct(m['localisation_within_1'])} | {pct(m['localisation_same_line'])} | "
                         f"{num(m['latency_ms']['mean'])} / {num(m['latency_ms']['p95'])} |")
        L.append("")
    else:
        L.append(f"Not run: {cp.get('availability', {}).get('reason', 'unknown')}\n")

    if s.get("paired_tests"):
        L.append("## Paired bootstrap differences (test split)\n")
        L.append("| Comparison | Mean difference | 95% CI |")
        L.append("|---|---|---|")
        for k, v in s["paired_tests"].items():
            L.append(f"| {k} | {num(v['diff'], 4)} | [{num(v['ci95'][0], 4)}, {num(v['ci95'][1], 4)}] |")
        L.append("")

    if s.get("test_by_category"):
        L.append("## Test results by error category\n")
        L.append("| Category | n | C top-1 | P top-1 | P top-3 | P coverage | P false confident |")
        L.append("|---|---|---|---|---|---|---|")
        for g, e in s["test_by_category"].items():
            L.append(f"| {g} | {e['n']} | {100 * e['C']['top1_ast']:.0f}% | {100 * e['P']['top1_ast']:.0f}% | "
                     f"{100 * e['P']['top3_ast']:.0f}% | {100 * e['P']['coverage']:.0f}% | "
                     f"{100 * e['P']['false_confident']:.0f}% |")
        L.append("")
        L.append("## Test results by a-priori ambiguity label\n")
        L.append("| Label | n | C top-1 | P top-1 | P top-3 | P coverage | P false confident |")
        L.append("|---|---|---|---|---|---|---|")
        for g, e in s["test_by_ambiguity"].items():
            L.append(f"| {g} | {e['n']} | {100 * e['C']['top1_ast']:.0f}% | {100 * e['P']['top1_ast']:.0f}% | "
                     f"{100 * e['P']['top3_ast']:.0f}% | {100 * e['P']['coverage']:.0f}% | "
                     f"{100 * e['P']['false_confident']:.0f}% |")
        L.append("")
    if s.get("failure_examples"):
        L.append("## Examples of false confident recommendations (test)\n")
        L.append("| Case | Category | Injected mutation | IntelliFix repair | Margin |")
        L.append("|---|---|---|---|---|")
        for f in s["failure_examples"]:
            L.append(f"| {f['id']} | {f['category']} | `{f['injected']}` | `{f['parallax_repair']}` | {num(f['margin'])} |")
        L.append("")
    ts_table = s["tau_selection"]["table"]
    L.append("## Threshold selection table (dev split, system P)\n")
    L.append("| tau | coverage | selective risk | recommended | wrong |")
    L.append("|---|---|---|---|---|")
    for t in ts_table:
        L.append(f"| {t['tau']} | {100 * t['coverage']:.1f}% | {100 * t['selective_risk']:.1f}% | {t['recommended']} | {t['wrong']} |")
    L.append("")
    path.write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    src = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / "results" / "summary.json")
    write_report(json.loads(src.read_text()), src.with_name("report.md"))
